const modal = document.getElementById("archiveModal");
const modalTitle = document.getElementById("modalTitle");
const modalCode = document.getElementById("modalCode");
const modalDescription = document.getElementById("modalDescription");
const modalGallery = document.getElementById("modalGallery");
const modalClose = document.getElementById("modalClose");
const toast = document.getElementById("toast");

function showToast(message) {
    toast.textContent = message;
    toast.classList.add("show");

    window.clearTimeout(showToast.timer);
    showToast.timer = window.setTimeout(() => {
        toast.classList.remove("show");
    }, 2200);
}

function openArchive(key) {
    const item = archiveData[key];
    if (!item) return;

    modalCode.textContent = item.code;
    modalTitle.textContent = item.title;
    modalDescription.textContent = item.description;
    modalGallery.replaceChildren();

    item.images.forEach((image, index) => {
        const card = document.createElement("div");
        card.className = "gallery-item";

        const img = document.createElement("img");
        img.src = image.src;
        img.alt = image.alt;
        img.loading = "lazy";

        // 如果暂时没有替换图片，就显示设计占位图
        img.addEventListener("error", () => {
            img.removeAttribute("src");
            img.alt = "请替换为自己的作品图片";
            img.style.background =
                "linear-gradient(135deg, #1b3552, #101827 65%, #263e58)";
        }, { once: true });

        const caption = document.createElement("div");
        caption.className = "gallery-caption";

        const label = document.createElement("span");
        label.textContent = image.caption;

        const number = document.createElement("span");
        number.textContent = String(index + 1).padStart(2, "0");

        caption.append(label, number);
        card.append(img, caption);
        modalGallery.append(card);
    });

    modal.classList.add("open");
    modal.setAttribute("aria-hidden", "false");
    document.body.style.overflow = "hidden";
    modalClose.focus();
}

function closeArchive() {
    modal.classList.remove("open");
    modal.setAttribute("aria-hidden", "true");
    document.body.style.overflow = "";
}

document.querySelectorAll(".folder-card").forEach((button) => {
    button.addEventListener("click", () => {
        openArchive(button.dataset.folder);
    });
});

modalClose.addEventListener("click", closeArchive);

modal.addEventListener("click", (event) => {
    if (event.target.dataset.close === "true") {
        closeArchive();
    }
});

document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
        closeArchive();
    }
});

// 档案分类筛选
document.querySelectorAll(".filter-btn").forEach((button) => {
    button.addEventListener("click", () => {
        const filter = button.dataset.filter;

        document.querySelectorAll(".filter-btn").forEach((item) => {
            item.classList.toggle("active", item === button);
        });

        document.querySelectorAll(".folder-card").forEach((card) => {
            const matched =
                filter === "all" || card.dataset.category === filter;
            card.hidden = !matched;
        });

        showToast(filter === "all" ? "ALL FILES DISPLAYED" : "FILTER APPLIED");
    });
});

// 自媒体账号链接：替换成自己的主页链接
const mediaLinks = {
    bilibili: "https://www.bilibili.com/",
    douyin: "https://www.douyin.com/",
    xiaohongshu: "https://www.xiaohongshu.com/"
};

document.querySelectorAll("[data-link]").forEach((link) => {
    const key = link.dataset.link;
    link.href = mediaLinks[key] || "#";
    link.target = "_blank";
    link.rel = "noopener noreferrer";

    link.addEventListener("click", (event) => {
        if (!mediaLinks[key] || mediaLinks[key].endsWith(".com/")) {
            event.preventDefault();
            showToast("REMEMBER TO ADD YOUR PROFILE URL");
        }
    });
});

// 鼠标光效：仅在支持鼠标的设备上启用
const cursorGlow = document.getElementById("cursorGlow");

if (window.matchMedia("(pointer: fine)").matches) {
    document.addEventListener("pointermove", (event) => {
        cursorGlow.style.left = event.clientX + "px";
        cursorGlow.style.top = event.clientY + "px";
    });
} else {
    cursorGlow.style.display = "none";
}

